import { build, context } from "esbuild";

const watch = process.argv.includes("--watch");

const providers = [{ globalName: "ViuProvider", name: "viu" }];

for (const provider of providers) {
	const options = {
		banner: {
			js: `/* ${provider.name} provider for Nuvio - generated by build.mjs, do not edit here. */`,
		},
		bundle: true,
		charset: "utf8",
		entryPoints: [`src/${provider.name}/index.js`],
		footer: {
			js: [
				";(function (provider) {",
				'  if (typeof module !== "undefined" && module && module.exports) {',
				"    module.exports.getStreams = provider.getStreams;",
				"    module.exports.onSettings = provider.onSettings;",
				"  }",
				'  if (typeof globalThis !== "undefined") {',
				"    globalThis.getStreams = provider.getStreams;",
				"    globalThis.onSettings = provider.onSettings;",
				"  }",
				`})(${provider.globalName});`,
			].join("\n"),
		},
		format: "iife",
		globalName: provider.globalName,
		legalComments: "none",
		outfile: `providers/${provider.name}.js`,
		platform: "neutral",
		target: ["es2020"],
	};

	if (watch) {
		const builder = await context(options);
		await builder.watch();
		console.log(
			`Watching src/${provider.name} -> providers/${provider.name}.js`,
		);
	} else {
		await build(options);
		console.log(`Built providers/${provider.name}.js`);
	}
}
